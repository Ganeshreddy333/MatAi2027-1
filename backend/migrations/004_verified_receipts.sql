CREATE TABLE IF NOT EXISTS matai_payment_verifications (
    registration_reference VARCHAR(80) NOT NULL,
    provider_order_id VARCHAR(64) NULL,
    provider_payment_id VARCHAR(64) NULL,
    payment_method VARCHAR(40) NULL,
    amount_minor BIGINT UNSIGNED NOT NULL,
    currency CHAR(3) NOT NULL,
    access_token_hash CHAR(64) NOT NULL,
    checkout_verified TINYINT(1) NOT NULL DEFAULT 0,
    webhook_verified TINYINT(1) NOT NULL DEFAULT 0,
    razorpay_verified TINYINT(1) NOT NULL DEFAULT 0,
    financial_reconciled TINYINT(1) NOT NULL DEFAULT 0,
    database_validated TINYINT(1) NOT NULL DEFAULT 0,
    verification_status VARCHAR(32) NOT NULL DEFAULT 'INITIATED',
    receipt_number VARCHAR(80) NULL,
    receipt_generated_at DATETIME NULL,
    receipt_json JSON NULL,
    receipt_pdf MEDIUMBLOB NULL,
    paid_at DATETIME NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (registration_reference),
    UNIQUE KEY uq_matai_payment_verification_order (provider_order_id),
    UNIQUE KEY uq_matai_payment_verification_payment (provider_payment_id),
    UNIQUE KEY uq_matai_payment_verification_receipt (receipt_number),
    KEY idx_matai_payment_verification_status (verification_status, updated_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
